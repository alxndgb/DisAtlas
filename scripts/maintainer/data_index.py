"""Maintainer: data index. For every tracked file under data/ (README/checksum files and this index excluded) list the tracked code that
reads it, and write
  * data/DATA_INDEX.tsv  (path, bytes, read_by, read_by_folder, tested_by)
  * the "Read by" block of data/README.md, between the READ_BY markers (one row per folder).
A file counts as read when a code file names it (basename, its stem as a quoted/path token, or an f-string file-name template that
matches it in a file that also names its folder: read_by) or only names its folder (glob or directory reads: read_by_folder). Tests are listed separately and do not count as readers.

    python scripts/maintainer/data_index.py          # rewrite both
    python scripts/maintainer/data_index.py --check  # exit 1 if either is stale (tests/test_data_index.py)
"""
import os, re, subprocess, sys
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SKIP = (".md", "SHA256SUMS.txt", ".gitkeep", "DATA_INDEX.tsv")   # the index does not list itself: its size would never settle
CODE = (".py", ".ipynb", ".sh", ".sbatch", ".R")
EXT = r"(\.tsv|\.csv|\.json|\.parquet|\.npz|\.npy|\.gz|\.txt|\.pt|\.obo|\.owl|\.sha256)+$"
BEGIN, END = "<!-- READ_BY:BEGIN (generated by scripts/maintainer/data_index.py; do not edit) -->", "<!-- READ_BY:END -->"


def git_ls(*p):
    return subprocess.run(["git", "ls-files", *p], cwd=ROOT, capture_output=True, text=True, check=True).stdout.split()


def index():
    data = [f for f in git_ls("data") if not f.endswith(SKIP)]
    code = [f for f in git_ls() if f.endswith(CODE) and not f.startswith("data/") and f != "scripts/maintainer/data_index.py"]
    txt = {f: (ROOT / f).read_text(errors="ignore") for f in code}
    # f-string / format templates such as f"point_estimates_{pool}.tsv": {...} matches one path component
    tpl = {f: [re.compile("^" + ".+?".join(re.escape(p) for p in re.split(r"\{[^}]*\}", m)) + "$")
               for m in set(re.findall(r"[\"'/]([A-Za-z0-9_.\-]*\{[^}\"'\n]+\}[A-Za-z0-9_.{}\-]*\.[a-z]{2,7}(?:\.gz)?)[\"']", t))]
           for f, t in txt.items()}
    rows = []
    for d in data:
        base = os.path.basename(d); stem = re.sub(EXT, "", base); sub = os.path.dirname(d).split("/", 1)[-1]
        pat = re.compile(r"[\"'/{]" + re.escape(stem) + r"[\"'.{_]") if len(stem) > 6 else None
        leaf = sub.rsplit("/", 1)[-1]
        name = sorted(f for f, t in txt.items() if base in t or (pat and pat.search(t))
                      or (any(r.match(base) for r in tpl[f]) and re.search(r"[\"'/]" + re.escape(leaf) + r"[\"'/]", t)))
        fold = sorted(f for f, t in txt.items() if f not in name and re.search(r"[\"'/]" + re.escape(leaf) + r"[\"'/]", t))
        rows.append(OrderedDict(path=d, bytes=(ROOT / d).stat().st_size,
                                read_by=";".join(f for f in name if not f.startswith("tests/")),
                                read_by_folder=";".join(f for f in fold if not f.startswith("tests/")),
                                tested_by=";".join(f for f in name + fold if f.startswith("tests/"))))
    return rows


def render(rows):
    tsv = "\t".join(rows[0]) + "\n" + "".join("\t".join(str(v) for v in r.values()) + "\n" for r in rows)
    by = OrderedDict()
    for r in rows:
        k = os.path.dirname(r["path"]).split("/", 1)[-1]; by.setdefault(k, [[], set()])
        by[k][0].append(r); by[k][1].update(x for x in (r["read_by"] + ";" + r["read_by_folder"]).split(";") if x)
    md = [BEGIN, "", "| folder | files | read by |", "|---|---|---|"]
    for k, (rs, rd) in by.items():
        unread = [os.path.basename(r["path"]) for r in rs if not r["read_by"] and not r["read_by_folder"]]
        cell = ", ".join(f"`{x}`" for x in sorted(rd)) or "(none)"
        if unread: cell += " (not read by code: " + ", ".join(f"`{u}`" for u in unread) + ")"
        md.append(f"| `{k}/` | {len(rs)} | {cell} |")
    md += ["", f"Per-file list: [DATA_INDEX.tsv](DATA_INDEX.tsv).", END]
    return tsv, "\n".join(md)


def main(check=False):
    rows = index(); tsv, block = render(rows)
    readme = (ROOT / "data/README.md").read_text(); i, j = readme.find(BEGIN), readme.find(END)
    new_readme = readme[:i] + block + readme[j + len(END):] if i >= 0 and j > i else readme.rstrip("\n") + "\n\n## Read by\n\n" + block + "\n"
    old_tsv = (ROOT / "data/DATA_INDEX.tsv").read_text() if (ROOT / "data/DATA_INDEX.tsv").exists() else ""
    if check:
        stale = [n for n, a, b in (("data/DATA_INDEX.tsv", old_tsv, tsv), ("data/README.md", readme, new_readme)) if a != b]
        unread = [r["path"] for r in rows if not r["read_by"] and not r["read_by_folder"]]
        return stale, unread
    (ROOT / "data/DATA_INDEX.tsv").write_text(tsv); (ROOT / "data/README.md").write_text(new_readme)
    print(len(rows), "files;", sum(1 for r in rows if not r["read_by"] and not r["read_by_folder"]), "not read by code")


if __name__ == "__main__":
    if "--check" in sys.argv:
        s, u = main(True); print("stale:", s, "unread:", u); sys.exit(1 if s or u else 0)
    main()
