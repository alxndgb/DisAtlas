"""Maintainer: Zenodo manifest. One row per file of the Zenodo bundle (data/zenodo/), with size, SHA-256, the checksum
list(s) that cover it, whether it matches, and its data licence. Writes release/ZENODO_MANIFEST.tsv.

    python scripts/maintainer/zenodo_manifest.py           # write the manifest (needs data/zenodo)
    python scripts/maintainer/zenodo_manifest.py --check   # exit 1 if a file is uncovered, mismatched, or a listed file is missing
"""
import hashlib, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]; Z = ROOT / "data/zenodo"
LISTS = {  # checksum list -> directory its paths are relative to (README.md gives the commands)
    "data/ZENODO_SHA256SUMS.txt": Z,
    "data/ZENODO_MODEL_OUTPUTS_SHA256SUMS.txt": ROOT,
    "release/ZENODO_SHA256SUMS_rawgraph.txt": Z,
    "data/zenodo/model_outputs/SHA256SUMS": Z / "model_outputs",
}
LICENCE = {  # top-level Zenodo folder -> data licence (author decisions, see data/README.md)
    "event_time": "Event-time per-event inputs: CC BY-SA 3.0, inherits the ChEMBL share-alike terms (author decision 2026-11-15; author to confirm)",
    "figures_main": "author-generated data (CC BY 4.0 proposed)",
    "graph": "training graph / restricted sources (salted tokens): CC BY 4.0 for the derived salted edges only (author decision 2026-11-15; author to confirm; data-owner clearance pending)",
    "model": "author-generated data (CC BY 4.0 proposed)",
    "model_outputs": "author-generated data (CC BY 4.0 proposed)",
    "si_bio": "author-generated data; GO release dates (GO CC BY 4.0)",
    "ontology_term_term_distance": "Gene Ontology / HPO term distances (CC BY 4.0 / HPO licence, attribution and version; author to confirm)",
}

def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 22), b""): h.update(b)
    return h.hexdigest()

def main(check=False):
    cover, missing = {}, []
    for lst, base in LISTS.items():
        lp = ROOT / lst
        if not lp.exists(): continue
        for line in lp.read_text().splitlines():
            if not line.strip(): continue
            h, p = line.split(None, 1); p = p.lstrip("*").strip(); f = (base / p).resolve()
            if not f.exists(): missing.append((lst, p)); continue
            cover.setdefault(str(f.relative_to(Z)), []).append((lst, h))
    rows, bad = [], []
    for f in sorted(x for x in Z.rglob("*") if x.is_file()):
        r = str(f.relative_to(Z)); s = sha(f); c = cover.get(r, [])
        ok = bool(c) and all(h == s for _, h in c)
        if r in ("model_outputs/SHA256SUMS",): ok = True   # the per-folder list itself
        if not ok: bad.append(r)
        rows.append([r, str(f.stat().st_size), s, ";".join(sorted({l for l, _ in c})) or "NONE", "ok" if ok else ("uncovered" if not c else "MISMATCH"),
                     LICENCE.get(r.split("/")[0], "confirm")])
    print(len(rows), "files;", len(bad), "uncovered or mismatched;", len(missing), "listed but missing", bad[:10], missing[:10])
    if check: return bad, missing
    with open(ROOT / "release/ZENODO_MANIFEST.tsv", "w") as o:
        o.write("# Zenodo bundle manifest (generated by scripts/maintainer/zenodo_manifest.py). path is relative to data/zenodo/.\n")
        o.write("path\tbytes\tsha256\tchecksum_lists\tverified\tlicence\n")
        for r in rows: o.write("\t".join(r) + "\n")
        o.write(f"# total\t{sum(int(r[1]) for r in rows)}\t{len(rows)} files\n")
    return bad, missing

if __name__ == "__main__":
    b, m = main("--check" in sys.argv); sys.exit(1 if ("--check" in sys.argv and (b or m)) else 0)
